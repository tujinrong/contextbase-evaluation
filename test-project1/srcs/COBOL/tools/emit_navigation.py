"""POST the draft, then redirect to a GET address containing only opaque state and IDs."""
from emit_cobol import program
program('STNAV','''    IF R-DATA(F-ACTION) NOT = "OPTIONS" OR
      (R-DATA(F-NAVIGATION) NOT = "NEW" AND "EDIT")
      MOVE 400 TO APP-STATUS GOBACK END-IF
    CALL "STPOST" RETURNING RC END-CALL
    IF RC NOT = 1 MOVE 405 TO APP-STATUS GOBACK END-IF
    MOVE 0 TO STUDENT-ID
    IF R-DATA(F-NAVIGATION) = "EDIT"
      CALL "STINTEGER" USING R-VALUE(F-OPENSTUDENTID) STUDENT-ID
        RETURNING RC END-CALL
      IF RC NOT = 0 OR STUDENT-ID < 1
        MOVE 400 TO APP-STATUS GOBACK END-IF
    ELSE
      IF ROLE-CODE = 0 MOVE 403 TO APP-STATUS GOBACK END-IF
    END-IF
    CALL "STSTATE" END-CALL IF APP-STATUS NOT = 200 GOBACK END-IF
    MOVE ST-RAW TO SEARCH-PENDING MOVE "Search" TO STATE-KIND
    CALL "STSTATEIO" USING BY VALUE DB-HANDLE 3
      BY REFERENCE CONTEXT-ID STATE-KIND OWNER-VALUE SESSION-VALUE TAB-ID
        SEARCH-STATE BY VALUE LENGTH OF SEARCH-STATE
      BY REFERENCE CONTEXT-REVISION BY VALUE 30 RETURNING RC END-CALL
    IF RC NOT = 0 MOVE 409 TO APP-STATUS GOBACK END-IF
    MOVE "NavigationReady" TO APP-OUTCOME GOBACK.
''')
