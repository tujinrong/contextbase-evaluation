AUTH = '''    CALL "STSAMPLECHECK" RETURNING RC END-CALL
    IF RC NOT = 0 PERFORM INVALID-SESSION GOBACK END-IF
    CALL "STIDENTITY" USING OWNER-VALUE SESSION-VALUE ROLE-CODE
      CSRF-TOKEN RETURNING RC END-CALL
    IF RC NOT = 0 OR OWNER-DATA NOT = "sample-user" OR ROLE-CODE NOT = 2
      PERFORM INVALID-SESSION GOBACK END-IF
    IF R-NULL(F-TABID) = -1
      CALL "STRANDOM" USING TAB-ID RETURNING RC END-CALL
      IF RC NOT = 0 PERFORM INVALID-SESSION END-IF
    ELSE
      CALL "STHEX" USING R-VALUE(F-TABID) RETURNING RC END-CALL
      IF RC NOT = 0 OR R-LENGTH(F-TABID) NOT = 64
        PERFORM INVALID-SESSION
      ELSE MOVE R-DATA(F-TABID) TO TAB-ID END-IF
    END-IF
    GOBACK.
INVALID-SESSION.
    MOVE 401 TO APP-STATUS
    MOVE "E-COM-003: サンプル接続が無効または期限切れです。" TO ERROR-TEXT
    PERFORM ADD-ERROR.
'''

MAIN = '''    INITIALIZE APP TEXT-UI
    MOVE 200 TO APP-STATUS MOVE 1 TO APP-ERRORS-LENGTH
    MOVE "Search" TO VIEW-MODE MOVE "NORMAL" TO T-PANEL
    MOVE 1 TO T-DISPLAY-WINDOW T-MODAL-WINDOW
    PERFORM VARYING I FROM 1 BY 1 UNTIL I > 64
      MOVE -1 TO R-NULL(I)
    END-PERFORM
    CALL "STSAMPLEOPEN" RETURNING RC END-CALL
    IF RC NOT = 0 STOP RUN RETURNING 1 END-IF
    CALL "STAUTH" END-CALL
    IF APP-STATUS NOT = 200 PERFORM FINISH END-IF
    MOVE SESSION-DATA TO T-SESSION MOVE TAB-ID TO T-WINDOW-ID
    MOVE 132 TO T-COL MOVE 27 TO T-ROW
    CALL "STTERMOPEN" USING T-COL T-ROW RETURNING T-RC END-CALL
    IF T-RC < 0
      DISPLAY "E-COM-003: Windows Console 27x132 が必要です。"
      PERFORM FINISH
    END-IF
    CALL "STCONNECT" RETURNING DB-HANDLE END-CALL
    IF DB-HANDLE = NULL
      MOVE 503 TO APP-STATUS
      MOVE "E-COM-004: DBへ接続できません。接続設定を確認し再起動してください。"
        TO ERROR-TEXT PERFORM ADD-ERROR
    ELSE
      CALL "STCLOCK" END-CALL
      IF APP-STATUS = 200 CALL "STMCHECK" END-CALL END-IF
      IF APP-STATUS = 200
        MOVE "INITIAL" TO R-DATA(F-ACTION)
        MOVE 7 TO R-LENGTH(F-ACTION) MOVE 0 TO R-NULL(F-ACTION)
        CALL "STSRCH" END-CALL
      END-IF
    END-IF
    PERFORM UNTIL T-STOP NOT = 0
      PERFORM METADATA
      MOVE EDITOR-REVISION TO T-EDITOR-EXPECTED
      MOVE CONTEXT-REVISION TO T-EXPECTED
      IF VIEW-MODE = "Search" MOVE "SRC" TO T-SCREEN
      ELSE MOVE "REG" TO T-SCREEN END-IF
      CALL "STRENDER" END-CALL
      IF T-RC < 0 EXIT PERFORM END-IF
      CALL "STEVENT" END-CALL
      IF T-STOP NOT = 0 OR T-RC < 0 EXIT PERFORM END-IF
      IF T-ACTION = "MENU"
        CALL "STTEXTREQ" END-CALL
        IF APP-STATUS = 200 MOVE 1 TO T-STOP END-IF
      ELSE
      IF T-ACTION NOT = SPACES
        IF DB-HANDLE = NULL
          MOVE "E-COM-004: DB未接続です。再起動してください。" TO ERROR-TEXT
          PERFORM ADD-ERROR
        ELSE PERFORM REQUEST END-IF
      END-IF
      END-IF
    END-PERFORM
    PERFORM FINISH.
REQUEST.
    CALL "STTEXTREQ" END-CALL
    IF APP-STATUS NOT = 200 EXIT PARAGRAPH END-IF
    MOVE SPACES TO APP-OUTCOME APP-MESSAGE APP-ERRORS
    MOVE 0 TO APP-MESSAGE-LENGTH T-ERROR-COUNT T-ERROR-SEEN
    MOVE 1 TO APP-ERRORS-LENGTH
    INITIALIZE R-VALUE(F-CONFIRMED)
    MOVE -1 TO R-NULL(F-CONFIRMED)
    MOVE T-ACTION TO R-DATA(F-ACTION)
    COMPUTE R-LENGTH(F-ACTION) = FUNCTION LENGTH(FUNCTION TRIM(T-ACTION))
    MOVE 0 TO R-NULL(F-ACTION)
    CALL "STAUTH" END-CALL
    IF APP-STATUS NOT = 200 EXIT PARAGRAPH END-IF
    CALL "STCLOCK" END-CALL
    IF APP-STATUS NOT = 200 EXIT PARAGRAPH END-IF
    IF T-ACTION = "NEW" OR "OPEN"
      MOVE "OPTIONS" TO R-DATA(F-ACTION) MOVE 7 TO R-LENGTH(F-ACTION)
      IF T-ACTION = "NEW" MOVE "NEW" TO R-DATA(F-NAVIGATION)
        MOVE 3 TO R-LENGTH(F-NAVIGATION)
      ELSE MOVE "EDIT" TO R-DATA(F-NAVIGATION)
        MOVE 4 TO R-LENGTH(F-NAVIGATION) END-IF
      MOVE 0 TO R-NULL(F-NAVIGATION)
      MOVE T-DISPLAY-WINDOW TO SEARCH-WINDOW
      CALL "STNAV" END-CALL
      IF APP-STATUS NOT = 200 EXIT PARAGRAPH END-IF
      PERFORM METADATA
      IF T-ACTION = "NEW" MOVE "NEW" TO R-DATA(F-ACTION)
        MOVE 3 TO R-LENGTH(F-ACTION)
        INITIALIZE R-VALUE(F-STUDENTID) R-VALUE(F-EXPECTEDVERSION)
        MOVE -1 TO R-NULL(F-STUDENTID) R-NULL(F-EXPECTEDVERSION)
      ELSE MOVE "EDIT" TO R-DATA(F-ACTION) MOVE 4 TO R-LENGTH(F-ACTION)
        MOVE R-VALUE(F-OPENSTUDENTID) TO R-VALUE(F-STUDENTID) END-IF
      INITIALIZE R-VALUE(F-NAVIGATION) R-VALUE(F-EDITORID)
      MOVE -1 TO R-NULL(F-NAVIGATION) R-NULL(F-EDITORID)
      MOVE SPACES TO EDITOR-ID EDITOR-PENDING APP-OUTCOME
      CALL "STEDIT" END-CALL
      IF APP-STATUS = 200 CALL "STREF" END-CALL END-IF
      EXIT PARAGRAPH
    END-IF
    EVALUATE T-ACTION
      WHEN "INIT" MOVE "INITIAL" TO R-DATA(F-ACTION)
        MOVE 7 TO R-LENGTH(F-ACTION)
      WHEN "CREATE" WHEN "UPDATE"
        MOVE "SAVE" TO R-DATA(F-ACTION) MOVE 4 TO R-LENGTH(F-ACTION)
      WHEN "OPTIONS"
        IF VIEW-MODE = "Edit"
          MOVE "EDITOPTIONS" TO R-DATA(F-ACTION)
          MOVE 11 TO R-LENGTH(F-ACTION)
        END-IF
    END-EVALUATE
    IF VIEW-MODE = "Edit" CALL "STPROMPT" END-CALL END-IF
    IF APP-STATUS = 200 AND APP-OUTCOME NOT = "ActionConfirmation"
      AND "PromptCancelled"
      EVALUATE FUNCTION TRIM(R-DATA(F-ACTION))
        WHEN "RESET" WHEN "RELOAD" WHEN "EDITOPTIONS" WHEN "CANCEL"
          CALL "STEDIT" END-CALL
        WHEN "SAVE" WHEN "CONFIRM" CALL "STSAVE" END-CALL
        WHEN "DELETE" CALL "STDELT" END-CALL
        WHEN "INITIAL" WHEN "SEARCH" WHEN "PAGE" WHEN "CLEAR"
        WHEN "RESUME" WHEN "OPTIONS"
          IF VIEW-MODE = "Edit"
            INITIALIZE R-VALUE(F-EDITORID) R-VALUE(F-STUDENTID)
              R-VALUE(F-EXPECTEDVERSION) R-VALUE(F-CONFIRMATIONTOKEN)
            MOVE -1 TO R-NULL(F-EDITORID) R-NULL(F-STUDENTID)
              R-NULL(F-EXPECTEDVERSION) R-NULL(F-CONFIRMATIONTOKEN)
            MOVE SPACES TO EDITOR-ID EDITOR-PENDING
          END-IF
          CALL "STSRCH" END-CALL
          IF T-ACTION = "SEARCH" OR "CLEAR" OR "PAGE"
            MOVE 1 TO T-DISPLAY-WINDOW SEARCH-WINDOW
          ELSE MOVE FUNCTION MAX(1, SEARCH-WINDOW) TO T-DISPLAY-WINDOW END-IF
      END-EVALUATE
    END-IF
    IF APP-OUTCOME = "Saved"
      MOVE "I-STU-001: 保存しました。検索結果を確認してください。" TO APP-MESSAGE
      COMPUTE APP-MESSAGE-LENGTH = FUNCTION LENGTH(FUNCTION TRIM(APP-MESSAGE))
      INITIALIZE R-VALUE(F-EDITORID) R-VALUE(F-STUDENTID)
        R-VALUE(F-EXPECTEDVERSION) R-VALUE(F-CONFIRMATIONTOKEN)
      MOVE -1 TO R-NULL(F-EDITORID) R-NULL(F-STUDENTID)
        R-NULL(F-EXPECTEDVERSION) R-NULL(F-CONFIRMATIONTOKEN)
      MOVE SPACES TO EDITOR-ID EDITOR-PENDING
      PERFORM METADATA
      MOVE "RESUME" TO R-DATA(F-ACTION) MOVE 6 TO R-LENGTH(F-ACTION)
      CALL "STSRCH" END-CALL
      MOVE FUNCTION MAX(1, SEARCH-WINDOW) TO T-DISPLAY-WINDOW
    END-IF
    IF VIEW-MODE = "Edit" AND APP-STATUS = 200 AND
      (EDITOR-PENDING = SPACES OR LOW-VALUES)
      CALL "STREF" END-CALL END-IF
    MOVE "NORMAL" TO T-PANEL.
METADATA.
    MOVE TAB-ID TO R-DATA(F-TABID) MOVE 64 TO R-LENGTH(F-TABID)
    MOVE 0 TO R-NULL(F-TABID)
    IF CONTEXT-ID NOT = SPACES AND LOW-VALUES
      MOVE CONTEXT-ID TO R-DATA(F-CONTEXTID)
      MOVE 64 TO R-LENGTH(F-CONTEXTID) MOVE 0 TO R-NULL(F-CONTEXTID)
      MOVE CONTEXT-REVISION TO V PERFORM ID-AS-TEMP
      MOVE TMP-VALUE TO R-VALUE(F-CONTEXTREVISION)
    END-IF
    IF EDITOR-ID NOT = SPACES AND LOW-VALUES
      MOVE EDITOR-ID TO R-DATA(F-EDITORID)
      MOVE 64 TO R-LENGTH(F-EDITORID) MOVE 0 TO R-NULL(F-EDITORID)
      IF STUDENT-ID > 0
        MOVE STUDENT-ID TO V PERFORM ID-AS-TEMP
        MOVE TMP-VALUE TO R-VALUE(F-STUDENTID)
        MOVE EXPECTED-VERSION TO V PERFORM ID-AS-TEMP
        MOVE TMP-VALUE TO R-VALUE(F-EXPECTEDVERSION)
      END-IF
    END-IF.
FINISH.
    IF T-RC < 0 OR DB-HANDLE = NULL MOVE 1 TO T-STOP
    ELSE MOVE 0 TO T-STOP END-IF
    CALL "STTERMCLOSE" RETURNING T-RC END-CALL
    CALL "STCLOSE" USING BY VALUE DB-HANDLE END-CALL
    CALL "STSAMPLECLOSE" RETURNING RC END-CALL
    STOP RUN RETURNING T-STOP.
'''
